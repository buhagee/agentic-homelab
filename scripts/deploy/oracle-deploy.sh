#!/usr/bin/env bash
# scripts/deploy/oracle-deploy.sh
# Deploy the Qacey Oracle VPS stack (reverse proxy + monitoring).
#
# Architecture:
#   wireguard-oracle  — WireGuard server; home server connects as peer
#   oracle-traefik    — TLS termination for the configured domain; forwards via WireGuard
#   uptime-kuma       — External uptime monitoring
#
# Run ON the Oracle VPS:
#   sudo bash scripts/deploy/oracle-deploy.sh
#
# Pre-requisites:
#   1. sudo bash scripts/setup/server-setup-oracle.sh  (OS hardening + Docker)
#   2. Copy .env.oracle.example → .env.oracle and fill in all values
#
# Re-run any time to update config or pull new images.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
DATA_DIR="/opt/qacey"
COMPOSE_FILE="$REPO_ROOT/docker-compose.oracle.yml"
ENV_FILE="$REPO_ROOT/.env.oracle"
VERSIONS_FILE="$REPO_ROOT/versions.env"

info()    { echo "  [INFO] $*"; }
success() { echo "  [OK]   $*"; }
warn()    { echo "  [WARN] $*"; }
error()   { echo "  [ERR]  $*" >&2; exit 1; }

# ── Require root ──────────────────────────────────────────────────────────────
[[ $EUID -eq 0 ]] || error "Run with sudo: sudo bash scripts/oracle-deploy.sh"

# ── Require .env.oracle ───────────────────────────────────────────────────────
[[ -f "$ENV_FILE" ]] || error ".env.oracle not found. Copy .env.oracle.example:\n  cp .env.oracle.example .env.oracle && nano .env.oracle"

cd "$REPO_ROOT"

# Required host values. Validate before any container is removed.
set +u
source <(grep -E "^QACEY_DOMAIN=|^HOME_LAN_CIDR=|^ORACLE_IP=" "$ENV_FILE" 2>/dev/null || true)
set -u
if [[ -z "${QACEY_DOMAIN:-}" ]]; then
  error "QACEY_DOMAIN not set in .env.oracle"
fi
if [[ -z "${HOME_LAN_CIDR:-}" ]]; then
  error "HOME_LAN_CIDR not set in .env.oracle"
fi

echo ""
echo "═══════════════════════════════════════════════════"
echo "  Qacey Oracle Deploy"
echo "═══════════════════════════════════════════════════"

# ── 1. Create data directories ────────────────────────────────────────────────
info "Creating /opt/qacey data directories..."
mkdir -p "$DATA_DIR/traefik/oracle"
mkdir -p "$DATA_DIR/traefik/oracle/dynamic"
mkdir -p "$DATA_DIR/traefik/oracle/logs"
touch "$DATA_DIR/traefik/oracle/logs/access.log"
mkdir -p "$DATA_DIR/wireguard/oracle"
mkdir -p "$DATA_DIR/crowdsec-oracle/config"
mkdir -p "$DATA_DIR/crowdsec-oracle/data"
success "Directories ready: $DATA_DIR"

# ── 2. Fix acme.json — must be a file, not a directory ────────────────────────
ACME_JSON="$DATA_DIR/traefik/oracle/acme.json"
if [[ -d "$ACME_JSON" ]]; then
  warn "Removing corrupted acme.json directory (Docker created it as a dir)..."
  rm -rf "$ACME_JSON"
fi
if [[ ! -f "$ACME_JSON" ]]; then
  touch "$ACME_JSON"
  chmod 600 "$ACME_JSON"
  success "acme.json created (fresh — certs will be issued on first request)"
else
  chmod 600 "$ACME_JSON"
  success "acme.json exists (existing certs preserved)"
fi

# ── 3. WireGuard key generation + config ─────────────────────────────────────
# Keys are generated once and stored in .env.oracle.
# If already present, they are preserved (idempotent).
# Config is written to /opt/qacey/wireguard/oracle/wg_confs/wg0.conf
# so linuxserver/wireguard picks it up directly (no auto-generation mode).
info "Checking WireGuard keys and writing server config..."

# Source current env to check for existing keys
set +u
# shellcheck disable=SC1090
source <(grep -E "^WIREGUARD_|^ORACLE_IP" "$ENV_FILE" 2>/dev/null || true)
set -u

if [[ -z "${WIREGUARD_ORACLE_PRIVATE_KEY:-}" ]]; then
  info "  Generating Oracle WireGuard private key..."
  WIREGUARD_ORACLE_PRIVATE_KEY="$(wg genkey)"
  WIREGUARD_ORACLE_PUBLIC_KEY="$(echo "$WIREGUARD_ORACLE_PRIVATE_KEY" | wg pubkey)"
  # Write to .env.oracle
  if grep -q "^WIREGUARD_ORACLE_PRIVATE_KEY=" "$ENV_FILE"; then
    sed -i "s|^WIREGUARD_ORACLE_PRIVATE_KEY=.*|WIREGUARD_ORACLE_PRIVATE_KEY=${WIREGUARD_ORACLE_PRIVATE_KEY}|" "$ENV_FILE"
    sed -i "s|^WIREGUARD_ORACLE_PUBLIC_KEY=.*|WIREGUARD_ORACLE_PUBLIC_KEY=${WIREGUARD_ORACLE_PUBLIC_KEY}|" "$ENV_FILE"
  else
    echo "" >> "$ENV_FILE"
    echo "# WireGuard keys (generated by oracle-deploy.sh)" >> "$ENV_FILE"
    echo "WIREGUARD_ORACLE_PRIVATE_KEY=${WIREGUARD_ORACLE_PRIVATE_KEY}" >> "$ENV_FILE"
    echo "WIREGUARD_ORACLE_PUBLIC_KEY=${WIREGUARD_ORACLE_PUBLIC_KEY}" >> "$ENV_FILE"
  fi
  success "  Oracle WireGuard keys generated."
else
  success "  Oracle WireGuard keys already present."
fi

# Require home server public key — must be set in .env.oracle after first oracle-deploy run
HOME_PUBLIC_KEY="${WIREGUARD_HOME_PUBLIC_KEY:-}"
if [[ -z "$HOME_PUBLIC_KEY" ]]; then
  warn "  WIREGUARD_HOME_PUBLIC_KEY not set in .env.oracle yet."
  warn "  After deploying the home server, add to .env.oracle:"
  warn "    WIREGUARD_HOME_PUBLIC_KEY=<value from home server .env>"
  warn "  Then re-run oracle-deploy.sh to write the complete WireGuard config."
else
  info "  Home server public key found — writing complete WireGuard server config..."
fi

# Write wg0.conf for Oracle WireGuard server
# linuxserver/wireguard reads from /config/wg_confs/wg0.conf when present
WG_DIR="$DATA_DIR/wireguard/oracle/wg_confs"
mkdir -p "$WG_DIR"
chmod 700 "$DATA_DIR/wireguard/oracle"

WG_CONF="$WG_DIR/wg0.conf"
cat > "$WG_CONF" <<EOF
[Interface]
# Oracle VPS WireGuard server
# Tunnel IP: 10.100.0.1/24
Address = 10.100.0.1/24
PrivateKey = ${WIREGUARD_ORACLE_PRIVATE_KEY}
ListenPort = 51820

# Enable IP forwarding so traffic can reach the home server
PostUp   = iptables -A FORWARD -i wg0 -j ACCEPT; iptables -A FORWARD -o wg0 -j ACCEPT; iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE
PostDown = iptables -D FORWARD -i wg0 -j ACCEPT; iptables -D FORWARD -o wg0 -j ACCEPT; iptables -t nat -D POSTROUTING -o eth0 -j MASQUERADE

[Peer]
# Home server
PublicKey = ${HOME_PUBLIC_KEY:-PLACEHOLDER_SET_WIREGUARD_HOME_PUBLIC_KEY_IN_ENV_ORACLE}
# Route both the tunnel subnet AND the home LAN subnet through this peer
# This allows Oracle Traefik to reach 192.0.2.10 (home Traefik) via the tunnel
AllowedIPs = 10.100.0.2/32, ${HOME_LAN_CIDR}
EOF
chmod 600 "$WG_CONF"
success "  WireGuard server config written to $WG_CONF"

# ── 4. Stop any pre-existing named containers ─────────────────────────────────
for cname in oracle-traefik uptime-kuma wireguard-oracle pangolin gerbil crowdsec-oracle cs-oracle-bouncer; do
  if docker ps -a --format '{{.Names}}' | grep -q "^${cname}$"; then
    info "Removing existing container: $cname..."
    docker rm -f "$cname"
    success "Removed $cname"
  fi
done

# ── 5. Render dynamic Traefik config with secrets ─────────────────────────────
# Traefik's file provider does not support env var substitution.
# oracle-deploy.sh renders passthrough.yml (template in repo) → rendered file
# at /opt/qacey/traefik/oracle/dynamic/passthrough.yml with real values.
# The rendered directory is mounted into oracle-traefik (not the repo directory).
info "Rendering Traefik dynamic config with secrets..."

# Source all needed vars from .env.oracle
set +u
# shellcheck disable=SC1090
source <(grep -E "^CROWDSEC_ORACLE_LAPI_KEY=|^CROWDSEC_ORACLE_NET_IP=|^QACEY_DOMAIN=|^HOME_LAN_CIDR=" "$ENV_FILE" 2>/dev/null || true)
set -u

# CROWDSEC_ORACLE_NET_IP is always the static value (set later in step 6 if not present)
CROWDSEC_NET_IP="172.19.0.10"

# Generate key if not present yet (will be registered in step 6)
if [[ -z "${CROWDSEC_ORACLE_LAPI_KEY:-}" ]]; then
  info "  Generating new CrowdSec bouncer key..."
  CROWDSEC_ORACLE_LAPI_KEY="$(openssl rand -hex 32)"
  if grep -q "^CROWDSEC_ORACLE_LAPI_KEY=" "$ENV_FILE"; then
    sed -i "s|^CROWDSEC_ORACLE_LAPI_KEY=.*|CROWDSEC_ORACLE_LAPI_KEY=${CROWDSEC_ORACLE_LAPI_KEY}|" "$ENV_FILE"
  else
    echo "" >> "$ENV_FILE"
    echo "# CrowdSec bouncer key (generated by oracle-deploy.sh)" >> "$ENV_FILE"
    echo "CROWDSEC_ORACLE_LAPI_KEY=${CROWDSEC_ORACLE_LAPI_KEY}" >> "$ENV_FILE"
  fi
  success "  CrowdSec bouncer key generated and saved to .env.oracle"
else
  success "  CrowdSec bouncer key already present."
fi

# Render passthrough.yml: substitute ${CROWDSEC_ORACLE_LAPI_KEY} and ${CROWDSEC_ORACLE_NET_IP}
TEMPLATE="$REPO_ROOT/infrastructure/traefik/oracle/dynamic/passthrough.yml"
RENDERED="$DATA_DIR/traefik/oracle/dynamic/passthrough.yml"
sed \
  -e "s|\${CROWDSEC_ORACLE_LAPI_KEY}|${CROWDSEC_ORACLE_LAPI_KEY}|g" \
  -e "s|\${CROWDSEC_ORACLE_NET_IP}|${CROWDSEC_NET_IP}|g" \
  -e "s|\${QACEY_DOMAIN}|${QACEY_DOMAIN}|g" \
  "$TEMPLATE" > "$RENDERED"
chmod 600 "$RENDERED"
success "  Rendered passthrough.yml → $RENDERED (secrets substituted)"

# ── 6. Deploy stack ───────────────────────────────────────────────────────────
info "Pulling latest images..."
docker compose -f "$COMPOSE_FILE" --env-file "$VERSIONS_FILE" --env-file "$ENV_FILE" pull --quiet

# Start crowdsec-oracle first so we can register the bouncer key before oracle-traefik starts
info "Starting crowdsec-oracle first (to register bouncer key before Traefik starts)..."
docker compose -f "$COMPOSE_FILE" --env-file "$VERSIONS_FILE" --env-file "$ENV_FILE" up -d crowdsec-oracle

# ── 7. Register CrowdSec bouncer key + install AppSec collections ─────────────
echo ""
info "Configuring CrowdSec..."

# Write static IP to .env.oracle
if grep -q "^CROWDSEC_ORACLE_NET_IP=" "$ENV_FILE"; then
  sed -i "s|^CROWDSEC_ORACLE_NET_IP=.*|CROWDSEC_ORACLE_NET_IP=${CROWDSEC_NET_IP}|" "$ENV_FILE"
else
  echo "CROWDSEC_ORACLE_NET_IP=${CROWDSEC_NET_IP}" >> "$ENV_FILE"
fi
success "  CrowdSec oracle_net IP: ${CROWDSEC_NET_IP} (static — written to .env.oracle)"

# Wait for CrowdSec LAPI to be ready
info "  Waiting for CrowdSec LAPI to be ready (up to 45s)..."
WAITED=0
until docker exec crowdsec-oracle cscli bouncers list &>/dev/null; do
  sleep 3; WAITED=$((WAITED+3))
  [[ $WAITED -lt 45 ]] || { warn "CrowdSec not ready — check: docker logs crowdsec-oracle"; break; }
done

# Register bouncer key (idempotent) — must happen BEFORE oracle-traefik starts
if docker exec crowdsec-oracle cscli bouncers list 2>/dev/null | grep -q "oracle-traefik-bouncer"; then
  info "  Bouncer already registered — deleting and re-registering to ensure key matches..."
  docker exec crowdsec-oracle cscli bouncers delete oracle-traefik-bouncer 2>/dev/null || true
fi
docker exec crowdsec-oracle cscli bouncers add oracle-traefik-bouncer \
  --key "${CROWDSEC_ORACLE_LAPI_KEY}" 2>/dev/null \
  && success "  Bouncer 'oracle-traefik-bouncer' registered." \
  || warn "  Could not register bouncer — re-run oracle-deploy.sh once CrowdSec is ready."

# Install AppSec collections (U-12 — virtual patching + generic attack rules)
info "  Installing AppSec collections..."
docker exec crowdsec-oracle cscli collections install \
  crowdsecurity/appsec-virtual-patching \
  crowdsecurity/appsec-generic-rules 2>/dev/null \
  && success "  AppSec collections installed." \
  || warn "  AppSec install failed — run manually after deploy."

# Restart CrowdSec to pick up AppSec acquisition (acquis.yaml has appsec listener on :7422)
info "  Restarting crowdsec-oracle to activate AppSec listener..."
docker restart crowdsec-oracle
sleep 5

# Now start the rest of the stack — oracle-traefik starts with key already registered
info "Starting remaining oracle stack services..."
docker compose -f "$COMPOSE_FILE" --env-file "$VERSIONS_FILE" --env-file "$ENV_FILE" up -d

echo ""
success "Oracle stack deployed"
echo ""
docker compose -f "$COMPOSE_FILE" --env-file "$VERSIONS_FILE" --env-file "$ENV_FILE" ps

sleep 8
BOUNCER_ERRORS="$(docker logs oracle-traefik --tail 10 2>&1 | grep -i "error\|bouncer\|crowdsec" || true)"
if [[ -z "$BOUNCER_ERRORS" ]]; then
  success "  oracle-traefik started cleanly — bouncer plugin active."
else
  warn "  oracle-traefik log output:"
  echo "$BOUNCER_ERRORS"
fi

# ── 8. Show status and next steps ────────────────────────────────────────────
echo ""
echo "═══════════════════════════════════════════════════"
echo "  WireGuard Status"
echo "═══════════════════════════════════════════════════"
echo ""
docker exec wireguard-oracle wg show 2>/dev/null || warn "WireGuard not ready yet — check: docker logs wireguard-oracle"

echo ""
echo "═══════════════════════════════════════════════════"
echo "  CrowdSec Status"
echo "═══════════════════════════════════════════════════"
echo ""
docker exec crowdsec-oracle cscli bouncers list 2>/dev/null || true

echo ""
echo "═══════════════════════════════════════════════════"
echo "  Next steps"
echo "═══════════════════════════════════════════════════"
echo ""
echo "  1. On the home server, run:"
echo "     sudo bash scripts/setup/server-setup-home.sh"
echo "     sudo bash scripts/setup/setup-wireguard-home.sh"
echo "     bash scripts/start.sh"
echo ""
echo "  2. Verify tunnel from Oracle VPS:"
echo "     docker exec wireguard-oracle wg show"
echo "     (should show home server peer with a recent handshake)"
echo ""
echo "  3. Cloudflare DNS cutover:"
echo "     - Add wildcard A record: *.${QACEY_DOMAIN} → ${ORACLE_IP:-<oracle-public-ip>} (grey cloud)"
echo "     - platform-status.${QACEY_DOMAIN} already points here — no change needed"
echo ""
echo "  4. Verify external access:"
echo "     curl -I https://vault.${QACEY_DOMAIN}"
echo ""
echo "  5. Enable AdGuard DHCP in the AdGuard admin UI"
echo ""
